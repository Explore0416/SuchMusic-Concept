/// 取位置 [pos] 处的 mask 字节（与 C++ 实现逐行对应）。
int kgmMaskAt(int pos) {
  var offset = pos >> 4;
  var value = 0;
  while (offset >= 0x11) {
    value ^= _table1[offset % 272];
    offset >>= 4;
    value ^= _table2[offset % 272];
    offset >>= 4;
  }
  return _maskV2PreDef[pos % 272] ^ value;
}

/// 仅供测试：暴露表长，确保与算法要求的 272 对齐。
const int kgmMaskTableLength = 272;

/// 给定块号（`pos >> 4`）返回该块的附加 value。
///
/// 同一 16 字节块内 offset 不变，因此每块只需算一次 —— 这是把逐字节
/// 解密从「每字节一次循环」降到「每 16 字节一次」的关键。
int kgmBlockValue(int block) {
  var offset = block;
  var value = 0;
  while (offset >= 0x11) {
    value ^= _table1[offset % 272];
    offset >>= 4;
    value ^= _table2[offset % 272];
    offset >>= 4;
  }
  return value;
}

/// mask 预定义值（按 `pos % 272` 取）。
int kgmMaskPreDef(int pos) => _maskV2PreDef[pos % 272];
